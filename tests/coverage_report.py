import json
import sys
from pathlib import Path

from coverage import excluded_section_names, load_code_labels

EXIT_SUCCESS = 0
EXIT_USAGE = 2
def percentage(part, whole):
    return 100.0 * part / whole if whole else 0.0


def load_result(path):
    return json.loads(Path(path).read_text())


def section_statistics(labels, hits):
    statistics = {}
    for name, (section, _) in labels.items():
        covered, total = statistics.get(section, (0, 0))
        statistics[section] = (covered + (name in hits), total + 1)
    return statistics


def write_summary(summary_path, hits, labels, unit, flow, debug):
    summary = {
        "label_coverage": round(percentage(len(hits), len(labels)), 1),
        "labels_covered": len(hits),
        "labels_total": len(labels),
        "unit": {"passed": unit["passed"], "total": unit["total"]},
        "flow": {"passed": flow["passed"], "total": flow["total"]},
        "debug": {"passed": debug["passed"], "total": debug["total"]},
    }
    Path(summary_path).parent.mkdir(parents=True, exist_ok=True)
    Path(summary_path).write_text(json.dumps(summary, indent=2))


def write_report(output_directory, labels, hits, unit_hits, flow_hits, debug_hits, statistics):
    total = len(labels)
    covered = len(hits)
    lines = [
        "# Test coverage",
        "",
        "Generated by `make coverage`. Do not edit by hand.",
        "",
        "Coverage is measured on code **labels** (routines and branch targets) that the program reaches at least once while the test suites run on the emulator. It is not line coverage, and it does not measure data values. The labels come from the debug build, which contains every label of the normal build plus the debug screen.",
        "",
        f"| Measure | Labels | Percentage |",
        f"|---|---|---|",
        f"| Total | {covered} / {total} | {percentage(covered, total):.1f}% |",
        f"| Unit tests only | {len(unit_hits & set(labels))} / {total} | {percentage(len(unit_hits & set(labels)), total):.1f}% |",
        f"| Flow tests only | {len(flow_hits & set(labels))} / {total} | {percentage(len(flow_hits & set(labels)), total):.1f}% |",
        f"| Debug flow tests only | {len(debug_hits & set(labels))} / {total} | {percentage(len(debug_hits & set(labels)), total):.1f}% |",
        "",
        "## By module",
        "",
        "| Module (section) | Labels covered | Percentage |",
        "|---|---|---|",
    ]
    for section in sorted(statistics):
        section_covered, section_total = statistics[section]
        lines.append(f"| {section} | {section_covered} / {section_total} | {percentage(section_covered, section_total):.1f}% |")
    lines += ["", "## Labels not reached", ""]
    missing = sorted((labels[name][0], name) for name in labels if name not in hits)
    if missing:
        lines += ["| Module | Label |", "|---|---|"]
        lines += [f"| {section} | `{name}` |" for section, name in missing]
    else:
        lines.append("None.")
    (Path(output_directory) / "COVERAGE.md").write_text("\n".join(lines) + "\n")


def main(arguments):
    if len(arguments) != 6:
        print("usage: coverage_report.py <debug_map> <unit_result> <flow_result> <debug_result> <docs_directory> <summary_file>")
        return EXIT_USAGE
    map_path, unit_path, flow_path, debug_path, output_directory, summary_path = arguments
    labels = load_code_labels(map_path, excluded_section_names("."))
    unit = load_result(unit_path)
    flow = load_result(flow_path)
    debug = load_result(debug_path)
    unit_hits = set(unit["hits"])
    flow_hits = set(flow["hits"])
    debug_hits = set(debug["hits"])
    hits = (unit_hits | flow_hits | debug_hits) & set(labels)
    statistics = section_statistics(labels, hits)
    overall = percentage(len(hits), len(labels))
    write_summary(summary_path, hits, labels, unit, flow, debug)
    write_report(output_directory, labels, hits, unit_hits, flow_hits, debug_hits, statistics)
    print(f"label coverage: {len(hits)} / {len(labels)} = {overall:.1f}%")
    return EXIT_SUCCESS


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
